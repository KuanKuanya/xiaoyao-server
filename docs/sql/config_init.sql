USE `xiaoyao_game`;

-- ================================================================
-- 一、地图配置表 (静态配置，无需乐观锁)
-- ================================================================

DROP TABLE IF EXISTS `t_cfg_map`;
CREATE TABLE `t_cfg_map` (
    `id` INT NOT NULL COMMENT '地图ID',
    `name` VARCHAR(32) NOT NULL COMMENT '地图名称',
    `req_realm_id` INT NOT NULL DEFAULT 1 COMMENT '解锁需要的境界ID',
    `recommend_realm` VARCHAR(32) NOT NULL DEFAULT '' COMMENT '推荐境界描述',
    `region` VARCHAR(32) DEFAULT NULL COMMENT '所属区域',
    `sub_region` VARCHAR(32) DEFAULT NULL COMMENT '子区域',
    `bg_image` VARCHAR(512) DEFAULT '' COMMENT '背景图URL',
    `description` VARCHAR(256) DEFAULT '' COMMENT '地图描述',
    `is_immortal` TINYINT(1) NOT NULL DEFAULT 0 COMMENT '是否仙界地图',
    `sort_order` INT NOT NULL DEFAULT 0 COMMENT '排序',
    -- 配置表状态控制
    `is_active` TINYINT(1) NOT NULL DEFAULT 1 COMMENT '是否启用',
    -- 公共字段 (配置表简化版)
    `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    `updated_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    PRIMARY KEY (`id`),
    KEY `idx_realm` (`req_realm_id`),
    KEY `idx_region` (`region`),
    KEY `idx_active` (`is_active`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='地图配置表';

-- ================================================================
-- 二、怪物配置表 (静态配置)
-- ================================================================

DROP TABLE IF EXISTS `t_cfg_monster`;
CREATE TABLE `t_cfg_monster` (
    `id` INT NOT NULL COMMENT '怪物ID',
    `name` VARCHAR(32) NOT NULL COMMENT '怪物名称',
    `monster_type` TINYINT NOT NULL DEFAULT 1 COMMENT '类型: 1普通 2精英 3领主 4世界BOSS',
    `realm_level` INT NOT NULL DEFAULT 0 COMMENT '怪物境界等级(用于计算属性)',
    -- 基础属性 (仙界怪物数值极大，需用BIGINT)
    `base_hp` BIGINT UNSIGNED NOT NULL DEFAULT 100 COMMENT '基础生命值',
    `base_atk` BIGINT UNSIGNED NOT NULL DEFAULT 10 COMMENT '基础攻击',
    `base_def` BIGINT UNSIGNED NOT NULL DEFAULT 5 COMMENT '基础防御',
    -- 奖励
    `exp_reward` BIGINT UNSIGNED NOT NULL DEFAULT 10 COMMENT '经验奖励',
    `stone_reward` BIGINT UNSIGNED NOT NULL DEFAULT 5 COMMENT '灵石奖励',
    -- 外观
    `icon` VARCHAR(16) DEFAULT '👹' COMMENT '怪物图标(emoji)',
    `avatar_url` VARCHAR(512) DEFAULT '' COMMENT '怪物头像URL',
    `description` VARCHAR(256) DEFAULT '' COMMENT '怪物描述',
    -- 配置表状态控制
    `is_active` TINYINT(1) NOT NULL DEFAULT 1 COMMENT '是否启用',
    -- 公共字段
    `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    `updated_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    PRIMARY KEY (`id`),
    KEY `idx_monster_type` (`monster_type`),
    KEY `idx_realm_level` (`realm_level`),
    KEY `idx_active` (`is_active`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='怪物配置表';

-- ================================================================
-- 三、地图-怪物关联表 (多对多)
-- ================================================================

DROP TABLE IF EXISTS `t_cfg_map_monster`;
CREATE TABLE `t_cfg_map_monster` (
    `id` INT NOT NULL AUTO_INCREMENT COMMENT '自增ID',
    `map_id` INT NOT NULL COMMENT '地图ID',
    `monster_id` INT NOT NULL COMMENT '怪物ID',
    `spawn_rate` INT NOT NULL DEFAULT 100 COMMENT '刷新权重(百分比)',
    `is_boss` TINYINT(1) NOT NULL DEFAULT 0 COMMENT '是否为地图BOSS',
    -- 公共字段
    `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    PRIMARY KEY (`id`),
    UNIQUE KEY `uk_map_monster` (`map_id`, `monster_id`),
    KEY `idx_map` (`map_id`),
    KEY `idx_monster` (`monster_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='地图怪物关联表';

-- ================================================================
-- 四、掉落配置表
-- ================================================================

DROP TABLE IF EXISTS `t_cfg_drop`;
CREATE TABLE `t_cfg_drop` (
    `id` INT NOT NULL AUTO_INCREMENT COMMENT '自增ID',
    `source_type` TINYINT NOT NULL COMMENT '来源类型: 1地图 2怪物 3BOSS',
    `source_id` INT NOT NULL COMMENT '来源ID',
    `item_id` INT NOT NULL COMMENT '物品ID',
    `drop_rate` INT NOT NULL DEFAULT 100 COMMENT '掉落概率(万分比, 10000=100%)',
    `min_count` INT NOT NULL DEFAULT 1 COMMENT '最小数量',
    `max_count` INT NOT NULL DEFAULT 1 COMMENT '最大数量',
    -- 公共字段
    `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    PRIMARY KEY (`id`),
    KEY `idx_source` (`source_type`, `source_id`),
    KEY `idx_item` (`item_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='掉落配置表';

-- ================================================================
-- 五、境界配置表 (与前端 RealmConfig 对应)
-- ================================================================

DROP TABLE IF EXISTS `t_cfg_realm`;
CREATE TABLE `t_cfg_realm` (
    `id` INT NOT NULL COMMENT '境界ID (从1开始)',
    `realm_index` INT NOT NULL DEFAULT 0 COMMENT '境界索引 (用于计算)',
    `name` VARCHAR(32) NOT NULL COMMENT '境界名称',
    `stage` VARCHAR(16) NOT NULL COMMENT '阶段: 初期/中期/后期/圆满',
    `tier` VARCHAR(16) NOT NULL COMMENT '大境界: 炼气/筑基/金丹等',
    -- 属性配置 (仙界数值极大，需用BIGINT)
    `base_hp` BIGINT UNSIGNED NOT NULL DEFAULT 100 COMMENT '基础生命',
    `base_atk` BIGINT UNSIGNED NOT NULL DEFAULT 10 COMMENT '基础攻击',
    `base_def` BIGINT UNSIGNED NOT NULL DEFAULT 5 COMMENT '基础防御',
    `max_exp` BIGINT UNSIGNED NOT NULL DEFAULT 100 COMMENT '升级所需经验',
    `exp_rate` DOUBLE NOT NULL DEFAULT 1.0 COMMENT '经验倍率',
    -- 突破配置
    `breakthrough_rate` INT NOT NULL DEFAULT 100 COMMENT '突破成功率(百分比)',
    `breakthrough_cost` BIGINT UNSIGNED NOT NULL DEFAULT 0 COMMENT '突破消耗灵石',
    -- 分类
    `is_immortal` TINYINT(1) NOT NULL DEFAULT 0 COMMENT '是否仙界境界',
    `sort_order` INT NOT NULL DEFAULT 0 COMMENT '排序',
    -- 配置表状态控制
    `is_active` TINYINT(1) NOT NULL DEFAULT 1 COMMENT '是否启用',
    -- 公共字段
    `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    `updated_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    PRIMARY KEY (`id`),
    KEY `idx_tier` (`tier`),
    KEY `idx_active` (`is_active`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='境界配置表';

-- ================================================================
-- 六、物品配置表
-- ================================================================

DROP TABLE IF EXISTS `t_cfg_item`;
CREATE TABLE `t_cfg_item` (
    `id` INT NOT NULL COMMENT '物品ID',
    `name` VARCHAR(32) NOT NULL COMMENT '物品名称',
    `item_type` TINYINT NOT NULL COMMENT '类型: 1装备 2丹药 3材料 4功法书 5宠物蛋 6消耗品',
    `quality` TINYINT NOT NULL DEFAULT 1 COMMENT '品质: 1白 2绿 3蓝 4紫 5橙 6红 7金',
    `icon` VARCHAR(16) DEFAULT '📦' COMMENT '图标(emoji)',
    `icon_url` VARCHAR(512) DEFAULT '' COMMENT '图标URL',
    `description` VARCHAR(256) DEFAULT '' COMMENT '物品描述',
    -- 基础属性
    `value` INT UNSIGNED NOT NULL DEFAULT 0 COMMENT '基础价值(售卖价)',
    `max_stack` INT NOT NULL DEFAULT 99 COMMENT '最大堆叠数',
    `bind_type` TINYINT NOT NULL DEFAULT 0 COMMENT '绑定类型: 0不绑 1装备绑 2拾取绑',
    -- 装备专属
    `equip_slot` VARCHAR(16) DEFAULT NULL COMMENT '装备槽位: WEAPON/ARMOR/HEAD/FEET/ARTIFACT',
    `req_realm_id` INT DEFAULT NULL COMMENT '装备需求境界',
    `stats` JSON DEFAULT NULL COMMENT '属性 {atk, def, hp, speed, ...}',
    -- 消耗品专属
    `use_effect` JSON DEFAULT NULL COMMENT '使用效果 {type, value}',
    `skill_id` INT DEFAULT NULL COMMENT '功法书关联技能ID',
    -- 配置表状态控制
    `is_active` TINYINT(1) NOT NULL DEFAULT 1 COMMENT '是否启用',
    -- 公共字段
    `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    `updated_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    PRIMARY KEY (`id`),
    KEY `idx_item_type` (`item_type`),
    KEY `idx_quality` (`quality`),
    KEY `idx_active` (`is_active`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='物品配置表';

